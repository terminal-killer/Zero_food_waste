/**
 * Converts a project blueprint into a comprehensive Hackathon PRD & Pitch Kit in Markdown format.
 */
export function exportToMarkdown(blueprint) {
  const { pitch, taskModelFit, architecture, pitchSlides, meta } = blueprint;

  return `# ${pitch.title} — Hackathon MVP PRD & Architecture Blueprint

> **Tagline:** ${pitch.tagline}  
> **Track:** ${pitch.track}  
> **Generated By:** ${meta.engine} on ${meta.generatedAt}

---

## 1. Executive Summary & Pitch

### Problem Statement
${pitch.problemStatement}

### Proposed Solution
${pitch.solutionStatement}

### Target Personas
${pitch.targetPersonas.map(p => `- ${p}`).join("\n")}

### Unfair Advantage & Moat
${pitch.unfairAdvantage}

### Key Validation Metrics
${pitch.keyMetrics.map(m => `- ${m}`).join("\n")}

---

## 2. Task-Model Fit Audit (@project-development)

- **Overall Fit Score:** ${taskModelFit.fitScore}/100 (${taskModelFit.verdict})
- **Synthesis Suitability:** ${taskModelFit.analysis.synthesisSuitability}
- **Subjective Reasoning:** ${taskModelFit.analysis.subjectiveJudgmentSuitability}
- **Deterministic Boundary:** ${taskModelFit.analysis.deterministicBoundary}
- **Hallucination Risk Mitigation:** ${taskModelFit.analysis.hallucinationRisk}
- **Latency Budget:** ${taskModelFit.analysis.latencyBudget}

### Component Division Matrix (LLM vs Deterministic Code)

| Component | Responsibility / Handler | Design Rationale |
|-----------|-------------------------|------------------|
${taskModelFit.llmVsCodeDivision.map(row => `| **${row.component}** | ${row.handling} | ${row.reason} |`).join("\n")}

---

## 3. Production Architecture (@senior-fullstack & @llm-app-patterns)

### Frontend Layer
- **Tech Stack:** ${architecture.frontend.framework}
- **State Management:** ${architecture.frontend.stateManagement}
- **Visual Design:** ${architecture.frontend.visualTokens}
- **Accessibility:** ${architecture.frontend.accessibility}

### Backend API Layer
- **Runtime:** ${architecture.backend.runtime}
- **Server Framework:** ${architecture.backend.framework}
- **Endpoints:** ${architecture.backend.modules.join(", ")}
- **Resilience:** ${architecture.backend.resilience}

### LLM Pipeline & Guardrails
- **Pattern:** ${architecture.llmAppPatterns.pattern}
- **Retrieval:** ${architecture.llmAppPatterns.retrievalMethod}
- **Chunking:** ${architecture.llmAppPatterns.chunkingStrategy}
- **Guardrails:**
${architecture.llmAppPatterns.guardrails.map(g => `  - ${g}`).join("\n")}

### Database Schema
\`\`\`sql
${architecture.databaseSchema.tables.map(t => `-- Table: ${t.name}\nCREATE TABLE ${t.name} (\n  ${t.columns.join(",\n  ")}\n);`).join("\n\n")}
\`\`\`

---

## 4. Pitch Deck Slide Outline

${pitchSlides.map(s => `### Slide ${s.slideNumber}: ${s.title}
*${s.subtitle}*
${s.bulletPoints.map(b => `- ${b}`).join("\n")}
`).join("\n")}

---

*Generated autonomously via IdeaSprint AI. Ready for immediate deployment.*
`;
}
